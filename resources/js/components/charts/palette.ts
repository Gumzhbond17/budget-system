/**
 * ຈານສີສຳລັບຂໍ້ມູນທີ່ແບ່ງເປັນກຸ່ມ (categorical) — ໃຊ້ເມື່ອ entity ບໍ່ມີສີຂອງ
 * ຕົນເອງໃນຖານຂໍ້ມູນ. ໝວດລາຍຈ່າຍມີ `expense_categories.color` ຢູ່ແລ້ວ ຈຶ່ງ
 * ບໍ່ໄດ້ໃຊ້ຈານນີ້ ແຕ່ **ແຫຼ່ງທຶນ (payers) ບໍ່ມີ** — ຈານນີ້ຈຶ່ງມີໄວ້ໃຫ້ມັນ.
 *
 * ຄ່າເຫຼົ່ານີ້ບໍ່ໄດ້ເລືອກດ້ວຍສາຍຕາ. ຜ່ານການກວດດ້ວຍເຄື່ອງມືກວດຈານສີ ທັງ
 * ໂໝດແຈ້ງ (ພື້ນ #ffffff) ແລະ ໂໝດມືດ (ພື້ນ #101828):
 *   - ຄູ່ທີ່ຕິດກັນທີ່ແຍກຍາກທີ່ສຸດສຳລັບຕາບອດສີ ΔE 9.1 (ແຈ້ງ) / 8.4 (ມືດ)
 *     — ເປົ້າໝາຍ ≥ 8
 *   - ຄູ່ທີ່ຕິດກັນສຳລັບຕາປົກກະຕິ ΔE 19.6 / 19.3 — ຂັ້ນຕ່ຳ ≥ 15
 *
 * ໂໝດມືດບໍ່ແມ່ນການພິກສີອັດຕະໂນມັດ — ເປັນ 6 ສີເກົ່າທີ່ເລືອກລະດັບຄວາມແຈ້ງ
 * ໃໝ່ໃຫ້ເໝາະກັບພື້ນມືດ ແລ້ວກວດເປັນຊຸດອີກຮອບ.
 *
 * ⚠️ ໃນໂໝດແຈ້ງ ສີຂຽວອ່ອນ/ເຫຼືອງ/ບົວ ມີ contrast ຕ່ຳກວ່າ 3:1 ເທິງພື້ນຂາວ —
 * ຈຶ່ງ **ຫ້າມ** ໃຊ້ຈານນີ້ກັບ chart ທີ່ບອກຄວາມໝາຍດ້ວຍສີຢ່າງດຽວ. ຕ້ອງມີ
 * ຊື່ ແລະ ຕົວເລກຂຽນໄວ້ນຳສະເໝີ (BreakdownDonut ມີຕາຕະລາງຂ້າງໆດ້ວຍເຫດຜົນນີ້).
 */
const CATEGORICAL_LIGHT = [
    '#2a78d6', // ຟ້າ
    '#eb6834', // ສົ້ມ
    '#1baf7a', // ຂຽວນ້ຳທະເລ
    '#eda100', // ເຫຼືອງ
    '#e87ba4', // ບົວ
    '#008300', // ຂຽວ
];

const CATEGORICAL_DARK = [
    '#3987e5',
    '#d95926',
    '#199e70',
    '#c98500',
    '#d55181',
    '#008300',
];

/**
 * ສີເທົາສະຫງວນ — ໃຊ້ກັບ "ອື່ນໆ" ແລະ "ບໍ່ໄດ້ລະບຸ" ເທົ່ານັ້ນ.
 * ຕັ້ງໃຈໃຫ້ອີ່ມສີຕ່ຳຈົນອ່ານອອກວ່າ "ບໍ່ແມ່ນກຸ່ມໃດກຸ່ມໜຶ່ງ" ບໍ່ແມ່ນສີຂອງກຸ່ມ.
 */
export const NEUTRAL_COLOR = '#94a3b8';

/**
 * ສີຂອງກຸ່ມໜຶ່ງ — ຜູກກັບ **ຕົວ entity** ບໍ່ແມ່ນຜູກກັບລຳດັບໃນ array.
 *
 * ເປັນຫຍັງຈຶ່ງສຳຄັນ: ຖ້າໃຊ້ index ຂອງ array ການກັ່ນຕອງ (ຫຼື ຍອດທີ່ປ່ຽນຈົນ
 * ລຳດັບສະຫຼັບກັນ) ຈະທາສີໃໝ່ໃຫ້ກຸ່ມທີ່ຍັງເຫຼືອ — ຜູ້ອ່ານທີ່ຈື່ວ່າ "ສີຟ້າ =
 * Sinexay" ຈະຖືກຫຼອກ. ໃຊ້ id ຈຶ່ງໄດ້ສີດຽວກັນທຸກຄັ້ງ.
 *
 * @param seed id ຂອງ entity — ຄ່າຕິດລົບ (ບໍ່ໄດ້ລະບຸ) ໄດ້ສີເທົາສະຫງວນ
 */
export function seriesColor(seed: number, isDark: boolean): string {
    if (seed < 0) {
        return NEUTRAL_COLOR;
    }

    const scale = isDark ? CATEGORICAL_DARK : CATEGORICAL_LIGHT;

    return scale[seed % scale.length];
}
